const GLOSSARY = {};
GLOSSARY_LIST.forEach(([t, y, d]) => { GLOSSARY[t] = { yomi: y, desc: d }; });

// 長い用語から先に照合する正規表現（英数字の用語は単語境界を考慮）
const GLOSSARY_RE = (() => {
  const terms = Object.keys(GLOSSARY).sort((a, b) => b.length - a.length);
  const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const parts = terms.map((t) => (/^[A-Za-z0-9-]+$/.test(t) ? `(?<![A-Za-z0-9-])${esc(t)}(?![A-Za-z0-9])` : esc(t)));
  return new RegExp(parts.join('|'), 'g');
})();
